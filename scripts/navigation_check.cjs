const {chromium}=require(process.env.PLAYWRIGHT_PACKAGE || '/home/vjranga/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('fs');
const base=process.env.QUEST_BASE_URL || 'http://127.0.0.1:8001';
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const values=Object.fromEntries(fs.readFileSync('.env.learners','utf8').trim().split('\n').map(l=>l.split('=')));
 await page.goto(base+'/login/');await page.locator('#id_username').fill('vjranga');await page.locator('#id_password').fill(values.VJRANGA_PASSWORD);
 await Promise.all([page.waitForURL(base+'/'),page.getByRole('button',{name:'Continue the quest'}).click()]);
 const before=await (await page.context().request.get(base+'/api/progress/')).json();
 await page.locator('.mission-list .mission-card').first().click();await page.waitForURL(base+'/missions/hello/');
 if(await page.locator('#previous-mission').count())throw Error('First mission points to invalid previous mission');
 if(await page.locator('.mission-map-grid a').count()!==10)throw Error('Not all ten missions available');
 if(await page.locator('.mission-map-grid [aria-current="page"]').getAttribute('data-mission')!=='hello')throw Error('Current mission marker wrong');
 await page.locator('#go-challenge').click();await page.locator('#code').fill('print("navigation draft")');await page.locator('#code').dispatchEvent('input');
 await page.locator('#mission-map > summary').click();
 await page.locator('[data-mission="variables"]').click();await page.waitForURL(base+'/missions/variables/');
 await page.locator('#mission-map > summary').click();
 await page.locator('#previous-mission').click();await page.waitForURL(base+'/missions/hello/');
 await page.locator('#challenge-tab').click();
 if(await page.locator('#code').inputValue()!=='print("navigation draft")')throw Error('Navigating away lost challenge draft');
 await page.locator('[data-back-to-lesson]').first().click();
 if(!await page.locator('#learn-pane').isVisible()||!await page.locator('#challenge-pane').isHidden())throw Error('Back to lesson failed');
 await page.locator('#mission-map > summary').click();
 await page.locator('[data-mission="final-mission"]').click();await page.waitForURL(base+'/missions/final-mission/');
 if(!await page.locator('#previous-mission').count())throw Error('Final mission missing previous link');
 await page.locator('#mission-map > summary').click();
 await page.locator('[data-mission="hello"]').click();await page.waitForURL(base+'/missions/hello/');
 await page.screenshot({path:'artifacts/navigation-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile navigation overflows');
 await page.screenshot({path:'artifacts/navigation-mobile.png',fullPage:true});
 await page.locator('#mission-map > summary').click();
 await page.getByRole('link',{name:'All missions ☷',exact:true}).click();await page.waitForURL(base+'/#missions');
 if(await page.locator('.mission-list .mission-card').count()!==10)throw Error('Journey list incomplete');
 const after=await (await page.context().request.get(base+'/api/progress/')).json();
 if(before.xp!==after.xp||before.completed!==after.completed)throw Error('Navigation changed scores');
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();console.log('Specific journey-card links, previous/next, all ten mission links, back-to-lesson, draft preservation, mobile and unchanged marks verified.');
})().catch(e=>{console.error(e.message);process.exit(1)});
