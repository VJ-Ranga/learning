const {chromium} = require(process.env.PLAYWRIGHT_PACKAGE || '/home/vjranga/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('fs');
const base = process.env.QUEST_BASE_URL || 'http://127.0.0.1:8001';
(async () => {
 const browser = await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
 const context = await browser.newContext({permissions:['clipboard-read','clipboard-write'],viewport:{width:1440,height:1100}});
 const page = await context.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const values=Object.fromEntries(fs.readFileSync('.env.learners','utf8').trim().split('\n').map(l=>l.split('=')));
 await page.goto(base+'/login/');
 await page.locator('#id_username').fill('vjranga');await page.locator('#id_password').fill(values.VJRANGA_PASSWORD);
 await Promise.all([page.waitForURL(base+'/'),page.getByRole('button',{name:'Continue the quest'}).click()]);
 await page.goto(base+'/missions/hello/');
 const promptButtons=page.locator('[data-prompt-kind="section"]');
 if(await promptButtons.count()!==3)throw Error('Each explanation step needs its own AI prompt');
 await promptButtons.first().click();
 const prompt=await page.evaluate(()=>navigator.clipboard.readText());
 if(!prompt.includes('What is a program?')||!prompt.includes('beginner'))throw Error('Copied prompt lacks this step context');
 await page.evaluate(()=>{navigator.clipboard.writeText=()=>Promise.reject(new Error('Clipboard unavailable'));});
 await promptButtons.nth(1).click();
 if(!await page.locator('#ai-prompt-dialog').isVisible())throw Error('Manual-copy fallback missing');
 if(!(await page.locator('#ai-prompt-text').inputValue()).includes('Send text to the terminal'))throw Error('Fallback prompt has wrong step');
 await page.locator('#close-ai-prompt').click();
 await page.locator('#go-challenge').click();
 await page.locator('input[name="quiz"][value="input"]').check();
 await page.locator('#check-question').click();
 await page.waitForFunction(()=>document.getElementById('checkpoint-feedback').textContent.includes('Not quite'));
 if(!await page.locator('.quiz-option.answer-wrong').count())throw Error('Wrong choice not labeled');
 await page.locator('input[name="quiz"][value="print"]').check();
 if(!await page.locator('#checkpoint-feedback').isHidden())throw Error('Feedback stays stale after choice changes');
 await page.locator('#check-question').click();
 await page.waitForFunction(()=>document.getElementById('checkpoint-feedback').textContent.includes('Correct'));
 const navigation=await page.locator('#next-mission-card').boundingBox();
 if(navigation.height<65)throw Error('Next mission is too small');
 await page.screenshot({path:'artifacts/feedback-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.screenshot({path:'artifacts/feedback-mobile.png',fullPage:true});
 // Check completion UI with a contract fixture; never write practice marks to a real learner account.
 await context.route('**/api/missions/hello/attempt/',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({score:100,passed:true,quiz_correct:true,correct_option:'print',quiz_explanation:'Each print writes a line.',details:[{passed:true,output:'Hello, Python!\n',error:''}],progress:{xp:100}})}));
 await page.locator('#code').fill('print("Hello, Python!")');
 await page.locator('#check-code').click();
 await page.waitForFunction(()=>document.getElementById('feedback').textContent.includes('Mission complete'),null,{timeout:120000});
 if(!await page.locator('#feedback').getByRole('link',{name:/Next mission/}).count())throw Error('Completion has no clear next action');
 if(!(await page.locator('#feedback').innerText()).includes('Program: 1/1'))throw Error('Program result not explicit');
 await page.locator('#code').fill('print("changed draft")');
 await page.locator('#code').dispatchEvent('input');
 if(!await page.locator('#feedback').isHidden())throw Error('Old completion remains after code changes');
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();console.log('Feedback, next action, step AI prompt clipboard, completion UI and mobile checks passed. No account marks submitted.');
})().catch(e=>{console.error(e.message);process.exit(1)});
